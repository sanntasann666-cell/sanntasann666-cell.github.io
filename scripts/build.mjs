import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fees = readFileSync(join(root, "js/fees.js"), "utf8").replace(/^export /gm, "");
const app = readFileSync(join(root, "js/app.js"), "utf8").replace(
  /import\s*\{[\s\S]*?\}\s*from\s*["']\.\/fees\.js["'];\s*/,
  ""
);
if (app.includes("import ")) {
  throw new Error("app.js still contains an import; update scripts/build.mjs");
}
mkdirSync(join(root, "js"), { recursive: true });
const out = `/* generated by scripts/build.mjs — do not edit by hand */\n${fees}\n${app}\n`;
writeFileSync(join(root, "js/bundle.js"), out);
console.log("wrote js/bundle.js", out.length, "bytes");
